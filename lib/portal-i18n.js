export const LANGS = ["it", "en"];

export function t(lang, key, vars = {}) {
  const s = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.it[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}

// Taal kiezen: ?lang=en|it (onthouden in cookie), anders cookie, anders Italiaans
export function useLang() {
  const [lang, setLang] = useState("it");
  useEffect(() => {
    try {
      const q = new URLSearchParams(window.location.search).get("lang");
      if (q && LANGS.includes(q)) {
        document.cookie = `jj_lang=${q}; Path=/; Max-Age=31536000; SameSite=Lax`;
        setLang(q);
        return;
      }
      const m = document.cookie.match(/(?:^|;\s*)jj_lang=(\w+)/);
      if (m && LANGS.includes(m[1])) setLang(m[1]);
    } catch {}
  }, []);
  return lang;
}

// Portaal van deze host: "neurotone" (members.…) of "lubrisense" (intimate.…). Eerst "neurotone" (zoals de
// server-render), meteen vóór het tekenen bijgewerkt → geen hydration-fouten en geen zichtbare flits.
const useIsoLayoutEffect = typeof window !== "undefined" ? useLayoutEffect : useEffect;
export function usePortalBrand() {
  const [brand, setBrand] = useState("neurotone");
  useIsoLayoutEffect(() => { setBrand(portalBrandKey()); }, []);
  return brand;
}

export const useT = () => {
  const lang = useLang();
  const brand = usePortalBrand();
  return { lang, brand, t: (key, vars) => brandText(t(lang, key, vars), brand, lang) };
};

